function playNote(ctx, freq, startTime, duration) {
    const oscillator = ctx.createOscillator();
    const gainNode = ctx.createGain();

    oscillator.connect(gainNode);
    gainNode.connect(ctx.destination);

    oscillator.type = 'sine';
    oscillator.frequency.value = freq;

    // Envelope
    gainNode.gain.setValueAtTime(0, startTime);
    gainNode.gain.linearRampToValueAtTime(0.3, startTime + 0.05);
    gainNode.gain.exponentialRampToValueAtTime(0.01, startTime + duration - 0.05);

    oscillator.start(startTime);
    oscillator.stop(startTime + duration);
}

function playHappyBirthday() {
    if (isPlaying) {
        isPlaying = false;
        const currentLang = document.documentElement.lang || 'th';
        musicBtn.querySelector('span:last-child').textContent = translations[currentLang].btnMusic;
        musicBtn.querySelector('.music-icon').textContent = '▶️';
        musicVisualizer.classList.remove('playing');
        if (audioContext) {
            audioContext.close();
            audioContext = null;
        }
        return;
    }

    audioContext = new (window.AudioContext || window.webkitAudioContext)();
    isPlaying = true;
    const currentLang = document.documentElement.lang || 'th';
    musicBtn.querySelector('span:last-child').textContent = translations[currentLang].btnMusicStop;
    musicBtn.querySelector('.music-icon').textContent = '⏸️';
    musicVisualizer.classList.add('playing');

    let currentTime = audioContext.currentTime + 0.1;

    // Play the song twice
    for (let repeat = 0; repeat < 2; repeat++) {
        happyBirthdayNotes.forEach(note => {
            playNote(audioContext, note.freq, currentTime, note.dur);
            currentTime += note.dur + 0.05;
        });
        currentTime += 0.5; // gap between repeats
    }

    // Calculate total duration
    let totalDuration = 0;
    happyBirthdayNotes.forEach(note => {
        totalDuration += note.dur + 0.05;
    });
    totalDuration = (totalDuration + 0.5) * 2;

    // Stop after playing
    setTimeout(() => {
        if (isPlaying) {
            isPlaying = false;
            const currentLang = document.documentElement.lang || 'th';
            musicBtn.querySelector('span:last-child').textContent = translations[currentLang].btnMusic;
            musicBtn.querySelector('.music-icon').textContent = '▶️';
            musicVisualizer.classList.remove('playing');
        }
    }, totalDuration * 1000);
}

