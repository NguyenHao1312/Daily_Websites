const confettiCanvas = document.getElementById('confetti-canvas');
const confettiCtx = confettiCanvas.getContext('2d');

function resizeCanvas() {
    confettiCanvas.width = window.innerWidth;
    confettiCanvas.height = window.innerHeight;
}
resizeCanvas();
window.addEventListener('resize', resizeCanvas);

const confettiColors = ['#ff6b9d', '#a29bfe', '#fdcb6e', '#fd79a8', '#00cec9', '#e17055', '#fab1a0', '#81ecec'];

class ConfettiPiece {
    constructor() {
        this.reset();
    }

    reset() {
        this.x = Math.random() * confettiCanvas.width;
        this.y = -20;
        this.size = Math.random() * 8 + 4;
        this.speedY = Math.random() * 2 + 1;
        this.speedX = Math.random() * 2 - 1;
        this.rotation = Math.random() * 360;
        this.rotationSpeed = Math.random() * 5 - 2.5;
        this.color = confettiColors[Math.floor(Math.random() * confettiColors.length)];
        this.shape = Math.random() > 0.5 ? 'rect' : 'circle';
        this.opacity = Math.random() * 0.7 + 0.3;
    }

    update() {
        this.y += this.speedY;
        this.x += this.speedX + Math.sin(this.y * 0.01) * 0.5;
        this.rotation += this.rotationSpeed;

        if (this.y > confettiCanvas.height + 20) {
            this.reset();
        }
    }

    draw(ctx) {
        ctx.save();
        ctx.translate(this.x, this.y);
        ctx.rotate((this.rotation * Math.PI) / 180);
        ctx.globalAlpha = this.opacity;
        ctx.fillStyle = this.color;

        if (this.shape === 'rect') {
            ctx.fillRect(-this.size / 2, -this.size / 4, this.size, this.size / 2);
        } else {
            ctx.beginPath();
            ctx.arc(0, 0, this.size / 3, 0, Math.PI * 2);
            ctx.fill();
        }

        ctx.restore();
    }
}

const confettiPieces = [];
const CONFETTI_COUNT = 60;

for (let i = 0; i < CONFETTI_COUNT; i++) {
    const piece = new ConfettiPiece();
    piece.y = Math.random() * confettiCanvas.height;
    confettiPieces.push(piece);
}

function animateConfetti() {
    confettiCtx.clearRect(0, 0, confettiCanvas.width, confettiCanvas.height);

    confettiPieces.forEach(piece => {
        piece.update();
        piece.draw(confettiCtx);
    });

    requestAnimationFrame(animateConfetti);
}

animateConfetti();

